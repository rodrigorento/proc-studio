"""Turn the Blender renders into the app's images and the Kotlin that looks them up.

    python3 art/export_android.py            # after rendering with farmkit.render.render_all("art/build/renders")

Writes WebPs (with transparency) to app/src/main/res/drawable-nodpi/, generates CropArt.kt, checks that every
image the app can ask for exists, and reports the total size. Needs Pillow.
"""
import re
import sys
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent
REPO = ART.parent
RENDERS = ART / "build" / "renders"
DRAWABLES = REPO / "app/src/main/res/drawable-nodpi"
KOTLIN = REPO / "app/src/main/java/com/example/projdiic/CropArt.kt"
QUALITY = 88  # lossy colour; the transparency is kept lossless
BUDGET_MB = 10.0

sys.path.insert(0, str(ART))
from farmkit import style  # noqa: E402  (style.py has no Blender imports)

def _stages() -> dict[str, list[str]]:
    """Stages per crop, as farmkit.crops.<crop>.STAGES defines them (those modules need Blender, so read the text)."""
    found = {}
    for path in sorted((ART / "farmkit/crops").glob("*.py")):
        block = re.search(r"^STAGES = \{\n(.*?)\n\}", path.read_text(), re.S | re.M)
        if block:
            found[path.stem] = re.findall(r'^    "(\w+)": \{', block.group(1), re.M)
    return found


STAGES = _stages()


def expected_images() -> list[str]:
    names = []
    for wet in ("wet", "dry"):
        for light in style.LIGHTS:
            names.append(f"bed_empty_{wet}_{light}")
            for crop, stages in STAGES.items():
                names += [f"crop_{crop}_{stage}_{wet}_{light}" for stage in stages]
    return names


def export() -> None:
    names = expected_images()
    missing = [name for name in names if not (RENDERS / f"{name}.png").exists()]
    if missing:
        raise SystemExit(f"{len(missing)} renders missing from {RENDERS}, e.g. {missing[:3]}")
    DRAWABLES.mkdir(parents=True, exist_ok=True)
    total = 0
    for name in names:
        out = DRAWABLES / f"{name}.webp"
        Image.open(RENDERS / f"{name}.png").convert("RGBA").save(out, "WEBP", quality=QUALITY, alpha_quality=100, method=6)
        total += out.stat().st_size
    KOTLIN.write_text(kotlin(names))
    mb = total / 1_000_000
    print(f"{len(names)} images, {mb:.1f} MB (budget {BUDGET_MB:.0f} MB) -> {DRAWABLES.relative_to(REPO)}")
    print(f"Generated {KOTLIN.relative_to(REPO)}")
    if mb > BUDGET_MB:
        print("Over budget: lower QUALITY or the render size in farmkit/style.py.")


TEMPLATE = """// Generated by art/export_android.py from the Blender renders. Don't edit by hand: re-run the export.
package com.example.projdiic

import androidx.annotation.DrawableRes

/** The farm's pre-rendered beds: each crop's stages, watered or dry, in each time of day. */
object CropArt {
CONSTANTS

    val LIGHTS = listOf(LIGHT_LIST)

    /** Each crop's growth stages, youngest first. */
    val STAGES: Map<String, List<String>> = mapOf(
STAGE_MAP
    )

    /** The light the field is shown in at an hour of the day (0-23). */
    fun lightAt(hour: Int): String = when (hour) {
HOUR_CASES
    }

    @DrawableRes
    fun bed(crop: String, stage: String, wet: Boolean, light: String): Int =
        images.getValue("crop_${crop}_${stage}_${wetness(wet)}_$light")

    @DrawableRes
    fun emptyBed(wet: Boolean, light: String): Int = images.getValue("bed_empty_${wetness(wet)}_$light")

    private fun wetness(wet: Boolean) = if (wet) "wet" else "dry"

    private val images: Map<String, Int> = mapOf(
IMAGE_MAP
    )
}
"""


def kotlin(names: list[str]) -> str:
    lights = list(style.LIGHTS)
    hour_cases = []
    wraps = None
    for light, settings in style.LIGHTS.items():
        start, end = settings["hours"]
        if start < end:
            hour_cases.append(f"        in {start} until {end} -> {light.upper()}")
        else:
            wraps = light
    if wraps is None:
        raise SystemExit("One light must run past midnight (its hours wrap, e.g. (20, 5)).")
    hour_cases.append(f"        else -> {wraps.upper()}")
    quoted = lambda items: ", ".join(f'"{item}"' for item in items)  # noqa: E731
    pieces = {
        "CONSTANTS": "\n".join(f'    const val {light.upper()} = "{light}"' for light in lights),
        "LIGHT_LIST": ", ".join(light.upper() for light in lights),
        "STAGE_MAP": "\n".join(f'        "{crop}" to listOf({quoted(stages)}),' for crop, stages in STAGES.items()),
        "HOUR_CASES": "\n".join(hour_cases),
        "IMAGE_MAP": "\n".join(f'        "{name}" to R.drawable.{name},' for name in names),
    }
    text = TEMPLATE
    for key, value in pieces.items():
        text = text.replace(key, value)
    return text


if __name__ == "__main__":
    export()
